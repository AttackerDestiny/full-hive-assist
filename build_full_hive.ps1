param([string]$PolicyPath,[string]$RuntimePath,[string]$OutputPath)
$ErrorActionPreference = 'Stop'
if (($PolicyPath -or $RuntimePath) -and -not $OutputPath) {
    throw 'An explicit OutputPath is required with candidate source overrides'
}
Push-Location $PSScriptRoot
try {
    if (-not $PolicyPath) { $PolicyPath=Join-Path $PSScriptRoot 'full_hive_policy.luau' }
    if (-not $RuntimePath) { $RuntimePath=Join-Path $PSScriptRoot 'full_hive_runtime.luau' }
    $policy = Get-Content -LiteralPath $PolicyPath -Raw
    $runtime = Get-Content -LiteralPath $RuntimePath -Raw
    $hiveView = Get-Content -LiteralPath hive_view_ui.luau -Raw
    $theme = Get-Content -LiteralPath feather_theme.luau -Raw
    $progressionPolicy = Get-Content -LiteralPath progression_policy.luau -Raw
    $progressionFacts = Get-Content -LiteralPath progression_facts.luau -Raw
    $progressionFunds = Get-Content -LiteralPath progression_funds.luau -Raw
    $progressionRuntime = Get-Content -LiteralPath progression_runtime.luau -Raw
    $atlasProgressionControl = Get-Content -LiteralPath atlas_progression_control.luau -Raw
    $versionMatch = [regex]::Match($runtime, 'local SCRIPT_VERSION = "(\d+\.\d+\.\d+)"')
    if (-not $versionMatch.Success) { throw 'Runtime SCRIPT_VERSION must use major.minor.patch' }
    $version = $versionMatch.Groups[1].Value
    $star = Get-Content -LiteralPath auto_use_star_egg.luau -Raw
    # The standalone helper and its inlined copy must share readiness semantics.
    $progress = (Get-Content -LiteralPath star_progress.luau -Raw).Replace("`r`n", "`n").Trim()
    $inlineProgress = [regex]::Matches($star.Replace("`r`n", "`n"), 'local StarProgress = \(function\(\)\n(.*?)\nend\)\(\)', [Text.RegularExpressions.RegexOptions]::Singleline)
    if ($inlineProgress.Count -ne 1 -or $inlineProgress[0].Groups[1].Value.Trim() -cne $progress) {
        throw 'Embedded StarProgress must match star_progress.luau before building'
    }
    # Apply host integration only when every reviewed hook has exactly one match.
    function Replace-StarHook([string]$Source, [string]$Needle, [string]$Replacement) {
        $hookCount = [regex]::Matches($Source, [regex]::Escape($Needle)).Count
        if ($hookCount -ne 1) { throw "Star integration hook must match once ($hookCount): $Needle" }
        return $Source.Replace($Needle, $Replacement)
    }
    $star = Replace-StarHook $star 'MaxStarEggs = 2,' 'MaxStarEggs = env.FullHiveStarBudget or 2,'
    $star = Replace-StarHook $star 'local function refill()' "local function refill()`n    if env.FullHiveRefill then return env.FullHiveRefill() end"
    $star = Replace-StarHook $star 'local function ensureJelly()' "local function ensureJelly()`n    if env.FullHiveRefill then stopped(); return env.FullHiveRefill() end"
    $star = Replace-StarHook $star 'assert(before > 0, "Item inventory empty")' ('assert(before > 0, "Item inventory empty")' + "`n    if item == ""RoyalJelly"" and env.FullHiveJellyReady then assert(env.FullHiveJellyReady(stats), ""Royal Jelly batch changed before spending"") end")
    $star = Replace-StarHook $star 'Cache:Set({"Eggs", item}, remaining)' ('Cache:Set({"Eggs", item}, remaining)' + "`n    if item == ""RoyalJelly"" and env.FullHiveJellySpent then env.FullHiveJellySpent(remaining) end")
    $star = Replace-StarHook $star 'local function useItem(target, item, phase)' "local function useItem(target, item, phase)`n    if env.FullHiveMove then env.FullHiveMove() end`n    if env.FullHiveNear then env.FullHiveNear() end"
    $star = Replace-StarHook $star 'local function stopped()' "local function stopped()`n    if env.FullHiveStop then env.AutoGiftedStarStop = true end"
    if ($star.Contains(']====]')) { throw 'Star source conflicts with long string delimiter' }
    $progressionSources = if ([version]$version -ge [version]'1.6.0') { "local createAtlasProgressionControl = (function()`n$atlasProgressionControl`nend)()`nlocal ProgressionPolicy = (function()`n$progressionPolicy`nend)()`nlocal createProgressionFacts = (function()`n$progressionFacts`nend)()`nlocal createProgression = (function()`n$progressionRuntime`nend)()`n" } else { '' }
    if ([version]$version -ge [version]'1.6.1') { $progressionSources="local ProgressionFunds = (function()`n$progressionFunds`nend)()`n"+$progressionSources }
    $bundle = "-- Full Hive Assist for Atlas / Arceus X Android / Potassium. Generated by build_full_hive.ps1.`n-- Version: $version`nlocal Policy = (function()`n$policy`nend)()`nlocal StarState = (function()`n$progress`nend)()`nlocal StarEggSource = [====[`n$star`n]====]`nlocal FeatherTheme = (function()`n$theme`nend)()`nlocal createHiveView = (function()`n$hiveView`nend)()`n$progressionSources$runtime"
    if ($bundle.Length -lt 50000 -or -not $bundle.StartsWith('-- Full Hive Assist')) { throw "Generated bundle is incomplete ($($bundle.Length) chars)" }
    if (-not $OutputPath) { $OutputPath=Join-Path $PSScriptRoot 'auto_full_hive_assist.luau' }
    $outputPath=[IO.Path]::GetFullPath($OutputPath)
    $tempPath = "$outputPath.tmp"
    [IO.File]::WriteAllText($tempPath, $bundle, [Text.UTF8Encoding]::new($false))
    if ((Get-Item -LiteralPath $tempPath).Length -lt 50000) { Remove-Item -LiteralPath $tempPath -Force; throw 'Temporary bundle write was truncated' }
    Move-Item -LiteralPath $tempPath -Destination $outputPath -Force
    if ((Get-Item -LiteralPath $outputPath).Length -lt 50000) { throw 'Final bundle write was truncated' }
} finally { Pop-Location }
