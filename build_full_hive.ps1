$ErrorActionPreference = 'Stop'
Push-Location $PSScriptRoot
try {
    $policy = Get-Content -LiteralPath full_hive_policy.luau -Raw
    $runtime = Get-Content -LiteralPath full_hive_runtime.luau -Raw
    $star = Get-Content -LiteralPath auto_use_star_egg.luau -Raw
    # Keep the existing Star Egg source intact on disk. Hooks only coordinate its host.
    $star = $star.Replace('MaxStarEggs = 2,', 'MaxStarEggs = env.FullHiveStarBudget or 2,')
    $star = $star.Replace('local function refill()', "local function refill()`n    if env.FullHiveRefill then return env.FullHiveRefill() end")
    $star = $star.Replace('local function useItem(target, item, phase)', "local function useItem(target, item, phase)`n    if env.FullHiveMove then env.FullHiveMove() end`n    if env.FullHiveNear then env.FullHiveNear() end")
    $star = $star.Replace('local function stopped()', "local function stopped()`n    if env.FullHiveStop then env.AutoGiftedStarStop = true end")
    if ($star.Contains(']====]')) { throw 'Star source conflicts with long string delimiter' }
    $bundle = "-- Full Hive Assist for Atlas / Arceus X Android / Potassium. Generated by build_full_hive.ps1.`nlocal Policy = (function()`n$policy`nend)()`nlocal StarEggSource = [====[`n$star`n]====]`n$runtime"
    if ($bundle.Length -lt 50000 -or -not $bundle.StartsWith('-- Full Hive Assist')) { throw "Generated bundle is incomplete ($($bundle.Length) chars)" }
    $outputPath = Join-Path $PSScriptRoot 'auto_full_hive_assist.luau'
    $tempPath = "$outputPath.tmp"
    [IO.File]::WriteAllText($tempPath, $bundle, [Text.UTF8Encoding]::new($false))
    if ((Get-Item -LiteralPath $tempPath).Length -lt 50000) { Remove-Item -LiteralPath $tempPath -Force; throw 'Temporary bundle write was truncated' }
    Move-Item -LiteralPath $tempPath -Destination $outputPath -Force
    if ((Get-Item -LiteralPath $outputPath).Length -lt 50000) { throw 'Final bundle write was truncated' }
} finally { Pop-Location }
